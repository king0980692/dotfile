#!/usr/bin/env bash
# yazi-theme-gen.sh — regenerate yazi/theme-dark.toml and yazi/theme-light.toml
#
# yazi only applies a [flavor] once it has worked out whether the terminal is
# light or dark, and it works that out by asking with OSC 11 — which herdr never
# answers inside a pane (verified: an empty reply). With no answer it applies no
# flavor at all, so inside herdr yazi fell back to its built-in colours.
#
# theme.toml, unlike a flavor, is applied unconditionally. So inline each
# flavour's palette into a full theme file and let bash/.bashrc point
# yazi/theme.toml at the right one (_yazi_theme_sync). Nothing is hand-coloured
# here: the palettes are copied from the flavor packages verbatim, with
# yazi/theme-overrides.toml merged on top.
#
# Run after updating the flavor packages.

set -euo pipefail

cfg=${XDG_CONFIG_HOME:-$HOME/.config}/yazi
cd "$cfg"

gen() { # $1 = flavor dir name, $2 = output file
  local flavor=$1 out=$2
  [ -f "flavors/$flavor/flavor.toml" ] || { echo "missing flavors/$flavor" >&2; exit 1; }
  FLAVOR_DIR=$flavor OUT=$out uv run --quiet --no-project --with tomli-w python - <<'PY'
import os, tomllib, tomli_w

flavor_dir, out = os.environ["FLAVOR_DIR"], os.environ["OUT"]

def merge(base, over):
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            merge(base[k], v)
        else:
            base[k] = v
    return base

with open(f"flavors/{flavor_dir}/flavor.toml", "rb") as f:
    theme = tomllib.load(f)
with open("theme-overrides.toml", "rb") as f:
    merge(theme, tomllib.load(f))

# The flavor also ships the syntax-highlight theme used for file previews;
# outside the flavor mechanism it has to be pointed at explicitly.
tm = f"flavors/{flavor_dir}/tmtheme.xml"
if os.path.exists(tm):
    theme.setdefault("preview", {})["syntect_theme"] = f"~/.config/yazi/{tm}"

theme.pop("flavor", None)  # no flavor indirection any more; this file is the theme

with open(out, "wb") as f:
    f.write(
        f"# GENERATED by leon_scripts/yazi-theme-gen.sh from flavors/{flavor_dir}\n"
        "# plus theme-overrides.toml. Edit those, not this file.\n".encode()
    )
    tomli_w.dump(theme, f)
print(f"  wrote {out} from {flavor_dir}")
PY
}

gen kanagawa.yazi theme-dark.toml
gen kanagawa-lotus.yazi theme-light.toml
